/**
 * Renders every Matemind logo and icon file from ink-mark.mjs (docs/brand/BRAND.md section 6).
 * Needs Playwright and Pillow-free Node only for PNGs: link a node_modules that has Playwright into
 * docs/brand/tools, then run `node docs/brand/tools/render-assets.mjs` from the repo root.
 * favicon.ico is written by the small Python step printed at the end.
 */
import { chromium } from 'playwright'
import { readFileSync, writeFileSync } from 'node:fs'
import { INK, INK_DARK, PAPER, markBody, markPaths, markSvg } from './ink-mark.mjs'

const A = 'docs/brand/assets/', W = 'web/public/', D = 'docs/public/', S = 'website/public/'
const svg = (body) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">${body}</svg>`
// The mark's ink sits in x 8-60, y 3-60; this centres it in a tile.
const centred = (body, scale) => `<g transform="translate(${32 - 34 * scale} ${32 - 31.5 * scale}) scale(${scale})">${body}</g>`

/** App icon: rice-paper tile, ink mark. `radius` 0 for platforms that round the icon themselves. */
export const appIcon = ({ id = 'ai', radius = 14.4, scale = 0.72, detail = true } = {}) =>
    svg(`<rect width="64" height="64"${radius ? ` rx="${radius}"` : ''} fill="${PAPER}"/>${centred(markBody({ id, detail }), scale)}`)

/** Browser icon: the small mark, ink following the colour scheme. */
const markAuto = () => markSvg({ id: 'fa', ink: 'var(--ink)', detail: false })
    .replace('<defs>', `<style>:root{--ink:${INK}}@media (prefers-color-scheme:dark){:root{--ink:${INK_DARK}}}</style><defs>`)

const files = {
    [A + 'matemind-mark.svg']: markSvg({ id: 'mm' }),
    [A + 'matemind-mark-dark.svg']: markSvg({ id: 'md', ink: INK_DARK }),
    [A + 'matemind-mark-small.svg']: markSvg({ id: 'ms', detail: false }),
    [A + 'matemind-mark-mono.svg']: markSvg({ id: 'mo', detail: false, mono: '#000' }),
    [A + 'matemind-app-icon.svg']: appIcon(),
    [W + 'icon.svg']: markAuto(),
    [S + 'icon.svg']: markAuto(),
    [D + 'logo.svg']: appIcon({ id: 'dl' }),
    [W + 'mask-icon.svg']: markSvg({ id: 'mk', detail: false, mono: '#000' }),
}
for (const [path, content] of Object.entries(files)) writeFileSync(path, content + '\n')

// Path data for the in-app <MatemindMark> component, so the app and the files never drift.
const full = markPaths({ detail: true }), small = markPaths({ detail: false })
writeFileSync('web/src/components/brand/matemindMarkPaths.ts', `// Generated by docs/brand/tools/render-assets.mjs from ink-mark.mjs. Do not edit by hand.
export const MARK_FULL = ${JSON.stringify(full, null, 4)} as const

export const MARK_SMALL = ${JSON.stringify(small, null, 4)} as const
`)

// Lockups: keep the wordmark paths and spacing of the committed files, swap the mark group.
const withMark = (file, id, ink) => {
    const text = readFileSync(A + file, 'utf8')
    // The mark group ends right before the wordmark path, which is shifted by translate(1152.86 0).
    return text.replace(/(<g transform="translate\(-152[^"]*">)[\s\S]*?(<\/g>)(?=<path[^>]*translate\(1152)/, `$1${markBody({ id, ink })}$2`)
}
writeFileSync(A + 'matemind-lockup.svg', withMark('matemind-lockup.svg', 'lk', INK))
writeFileSync(A + 'matemind-lockup-dark.svg', withMark('matemind-lockup-dark.svg', 'lkd', INK_DARK))

const browser = await chromium.launch()
const png = async (content, size, path, bg = 'transparent') => {
    const page = await browser.newPage({ viewport: { width: size, height: size } })
    await page.setContent(`<html><body style="margin:0;background:${bg}"><div style="width:${size}px;height:${size}px">${content.replace('<svg ', '<svg width="100%" height="100%" ')}</div></body></html>`)
    await page.screenshot({ path, omitBackground: bg === 'transparent' })
    await page.close()
}
await png(appIcon({ id: 'at', radius: 0 }), 180, W + 'apple-touch-icon-180x180.png')
await png(appIcon({ id: 'mx', radius: 0, scale: 0.56 }), 512, W + 'maskable-icon-512x512.png')
await png(appIcon({ id: 'p64', detail: false }), 64, W + 'pwa-64x64.png')
await png(appIcon({ id: 'p192' }), 192, W + 'pwa-192x192.png')
await png(appIcon({ id: 'p512' }), 512, W + 'pwa-512x512.png')
await png(appIcon({ id: 'a1k', radius: 0 }), 1024, A + 'matemind-app-icon-1024.png')
await png(markSvg({ id: 'r1' }), 512, A + 'matemind-mark-512.png')
await png(markSvg({ id: 'r2', ink: INK_DARK }), 512, A + 'matemind-mark-dark-512.png')
await png(markSvg({ id: 'bd', detail: false, mono: '#fff' }), 96, A + 'matemind-badge-96.png')
await png(markSvg({ id: 'bd2', detail: false, mono: '#fff' }), 96, W + 'badge-96x96.png')
for (const s of [16, 32, 48]) await png(appIcon({ id: `f${s}`, detail: false, scale: 0.8 }), s, `/tmp/mm-fav-${s}.png`)

// Social preview 1280x640: dark lockup, tagline.
const page = await browser.newPage({ viewport: { width: 1280, height: 640 } })
const lockup = readFileSync(A + 'matemind-lockup-dark.svg', 'utf8')
await page.setContent(`<html><body style="margin:0;background:#0e0e10;font-family:Geist,-apple-system,system-ui,sans-serif;display:flex;flex-direction:column;align-items:center;justify-content:center;height:640px;color:#a1a1aa">
<div style="width:720px;height:134px">${lockup.replace('<svg ', '<svg width="100%" height="100%" ')}</div>
<div style="margin-top:56px;font-size:31px;line-height:1.5;text-align:center">Say what you want. Matemind splits it up,<br/>keeps watch, and gives you the bottom line.</div>
<div style="position:absolute;bottom:40px;font-size:21px;color:#71717a">github.com/matemind/matemind</div></body></html>`)
await page.screenshot({ path: A + 'matemind-social.png' })
await browser.close()
console.log('rendered; now build favicon.ico from /tmp/mm-fav-{16,32,48}.png')
